  const STORAGE_KEY = 'agri_lang';
  let lang = localStorage.getItem(STORAGE_KEY) === 'fil' ? 'fil' : 'en';

  function t(key, vars) {
    const table = DICT[lang] || DICT.en;
    let text = table[key];
    if (text == null) text = DICT.en[key];
    if (text == null) return key;

    if (vars) {
      text = text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] != null ? String(vars[name]) : m));
    }
    return text;
  }

  function apply(root) {
    const scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });

    scope.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.setAttribute('placeholder', t(el.dataset.i18nPh));
    });

    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });

    scope.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.setAttribute('title', t(el.dataset.i18nTitle));
    });

    document.documentElement.lang = lang === 'fil' ? 'fil' : 'en';
  }

  function setLang(next, opts) {
    const value = next === 'fil' ? 'fil' : 'en';
    if (value === lang && !(opts && opts.force)) return;
    lang = value;
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* private mode */ }

    apply();
    document.dispatchEvent(new CustomEvent('agri:lang', { detail: { lang } }));
  }

  const toggle = () => setLang(lang === 'en' ? 'fil' : 'en');

  /** Locale-aware number and date formatting that follows the toggle. */
  const locale = () => (lang === 'fil' ? 'fil-PH' : 'en-PH');

  return {
    t,
    apply,
    setLang,
    toggle,
    locale,
    get lang() { return lang; },
  };
